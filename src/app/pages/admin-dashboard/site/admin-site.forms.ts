export function construirPayloadSitio(
  formulario: GuardarConfiguracionSitioPayload
): GuardarConfiguracionSitioPayload {
  return {
    ...formulario,
    slug: formulario.slug.trim(),
    nombreComercial: formulario.nombreComercial.trim(),
    dominioPrincipal: normalizarTextoOpcional(formulario.dominioPrincipal),
    logoUrl: normalizarTextoOpcional(formulario.logoUrl),
    descripcionCorta: normalizarTextoOpcional(formulario.descripcionCorta),
    colorPrimario: normalizarTextoOpcional(formulario.colorPrimario),
    colorSecundario: normalizarTextoOpcional(formulario.colorSecundario),
    fuenteTitulos: normalizarTextoOpcional(formulario.fuenteTitulos),
    fuenteCuerpo: normalizarTextoOpcional(formulario.fuenteCuerpo),
    heroTitulo: normalizarTextoOpcional(formulario.heroTitulo),
    heroSubtitulo: normalizarTextoOpcional(formulario.heroSubtitulo),
    heroImagenUrl: normalizarTextoOpcional(formulario.heroImagenUrl),
    heroTipoMedio: formulario.heroTipoMedio,
    heroVideoUrl: normalizarTextoOpcional(formulario.heroVideoUrl),
    heroAltura: formulario.heroAltura,
    heroEtiqueta: normalizarTextoOpcional(formulario.heroEtiqueta),
    heroAlineacion: formulario.heroAlineacion,
    heroOverlay: formulario.heroOverlay,
    heroTextoCta: normalizarTextoOpcional(formulario.heroTextoCta),
    heroAccionCta: formulario.heroAccionCta,
    heroEnlaceCta: normalizarTextoOpcional(formulario.heroEnlaceCta),
    heroTextoSecundario: normalizarTextoOpcional(formulario.heroTextoSecundario),
    heroAccionSecundaria: formulario.heroAccionSecundaria,
    heroEnlaceSecundario: normalizarTextoOpcional(formulario.heroEnlaceSecundario),
    inicioTituloServicios: normalizarTextoOpcional(formulario.inicioTituloServicios),
    inicioDescripcionServicios: normalizarTextoOpcional(formulario.inicioDescripcionServicios),
    inicioEtiquetaServicios: normalizarTextoOpcional(formulario.inicioEtiquetaServicios),
    inicioTextoVerServicios: normalizarTextoOpcional(formulario.inicioTextoVerServicios),
    inicioTextoReservar: normalizarTextoOpcional(formulario.inicioTextoReservar),
    inicioTituloContacto: normalizarTextoOpcional(formulario.inicioTituloContacto),
    inicioDescripcionContacto: normalizarTextoOpcional(formulario.inicioDescripcionContacto),
    inicioEtiquetaContacto: normalizarTextoOpcional(formulario.inicioEtiquetaContacto),
    inicioTextoAgenda: normalizarTextoOpcional(formulario.inicioTextoAgenda),
    inicioTextoWhatsapp: normalizarTextoOpcional(formulario.inicioTextoWhatsapp),
    inicioOrdenSecciones: formulario.inicioOrdenSecciones,
    seoTitulo: normalizarTextoOpcional(formulario.seoTitulo),
    seoDescripcion: normalizarTextoOpcional(formulario.seoDescripcion),
    whatsapp: normalizarTextoOpcional(formulario.whatsapp),
    whatsappMensaje: normalizarTextoOpcional(formulario.whatsappMensaje),
    telefono: normalizarTextoOpcional(formulario.telefono),
    correo: normalizarTextoOpcional(formulario.correo),
    direccion: normalizarTextoOpcional(formulario.direccion),
    instagramUrl: normalizarTextoOpcional(formulario.instagramUrl),
    facebookUrl: normalizarTextoOpcional(formulario.facebookUrl),
    xUrl: normalizarTextoOpcional(formulario.xUrl),
    tiktokUrl: normalizarTextoOpcional(formulario.tiktokUrl),
    chatTitulo: normalizarTextoOpcional(formulario.chatTitulo),
    chatSaludo: normalizarTextoOpcional(formulario.chatSaludo),
    tema: normalizarTema(formulario.tema),
    menuEstilo: formulario.menuEstilo,
    menuTextoCta: normalizarTextoOpcional(formulario.menuTextoCta),
    menuAccionCta: formulario.menuAccionCta,
    footerTexto: normalizarTextoOpcional(formulario.footerTexto)
  };
}

function normalizarTema(valor?: string | null): string {
  const tema = (valor || '').trim().toUpperCase();
  return ['BASE', 'MINIMAL', 'ELEGANTE', 'VIBRANTE'].includes(tema) ? tema : 'BASE';
}
