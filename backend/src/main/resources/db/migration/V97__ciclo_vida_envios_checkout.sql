CREATE TABLE envio_pedido (
    id BIGINT NOT NULL AUTO_INCREMENT,
    empresa_id BIGINT NOT NULL,
    checkout_orden_id BIGINT NOT NULL,
    sucursal_id BIGINT NOT NULL,
    proveedor VARCHAR(40) NOT NULL,
    ambiente VARCHAR(20) NOT NULL,
    estado VARCHAR(40) NOT NULL,
    motivo_bloqueo VARCHAR(500) NULL,
    paqueteria VARCHAR(80) NULL,
    servicio VARCHAR(120) NULL,
    numero_guia VARCHAR(160) NULL,
    url_etiqueta VARCHAR(1000) NULL,
    estado_rastreo VARCHAR(80) NULL,
    costo_proveedor DECIMAL(12,2) NULL,
    costo_cliente DECIMAL(12,2) NOT NULL DEFAULT 0,
    moneda VARCHAR(10) NOT NULL,
    intentos INT NOT NULL DEFAULT 0,
    ultimo_error VARCHAR(1000) NULL,
    creado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_envio_pedido_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_envio_pedido_checkout FOREIGN KEY (checkout_orden_id) REFERENCES checkout_orden(id),
    CONSTRAINT fk_envio_pedido_sucursal FOREIGN KEY (sucursal_id) REFERENCES sucursal(id),
    CONSTRAINT uk_envio_pedido_checkout UNIQUE (empresa_id, checkout_orden_id),
    INDEX idx_envio_pedido_estado (empresa_id, estado, actualizado_en),
    INDEX idx_envio_pedido_guia (empresa_id, numero_guia)
);
