CREATE TABLE checkout_orden (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id CHAR(36) NOT NULL,
    empresa_id BIGINT NOT NULL,
    sucursal_id BIGINT NOT NULL,
    zona_precio_id BIGINT NULL,
    idempotencia VARCHAR(128) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    correo_cliente VARCHAR(180) NOT NULL,
    moneda VARCHAR(10) NOT NULL,
    subtotal DECIMAL(12,2) NOT NULL,
    descuento_total DECIMAL(12,2) NOT NULL DEFAULT 0,
    impuestos_total DECIMAL(12,2) NOT NULL DEFAULT 0,
    total DECIMAL(12,2) NOT NULL,
    expira_en DATETIME(6) NOT NULL,
    creada_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    actualizada_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_checkout_orden_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_checkout_orden_sucursal FOREIGN KEY (sucursal_id) REFERENCES sucursal(id),
    CONSTRAINT fk_checkout_orden_zona FOREIGN KEY (zona_precio_id) REFERENCES producto_zona_precio(id),
    CONSTRAINT uk_checkout_orden_public_id UNIQUE (public_id),
    CONSTRAINT uk_checkout_orden_idempotencia UNIQUE (empresa_id, idempotencia),
    INDEX idx_checkout_orden_estado (empresa_id, estado, expira_en)
);

CREATE TABLE checkout_orden_detalle (
    id BIGINT NOT NULL AUTO_INCREMENT,
    checkout_orden_id BIGINT NOT NULL,
    empresa_id BIGINT NOT NULL,
    tipo_concepto VARCHAR(20) NOT NULL,
    producto_id BIGINT NULL,
    servicio_id BIGINT NULL,
    cita_id BIGINT NULL,
    nombre VARCHAR(180) NOT NULL,
    cantidad DECIMAL(14,3) NOT NULL,
    precio_lista_unitario DECIMAL(12,2) NOT NULL,
    precio_unitario DECIMAL(12,2) NOT NULL,
    descuento DECIMAL(12,2) NOT NULL DEFAULT 0,
    impuestos DECIMAL(12,2) NOT NULL DEFAULT 0,
    total DECIMAL(12,2) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_checkout_detalle_orden FOREIGN KEY (checkout_orden_id) REFERENCES checkout_orden(id) ON DELETE CASCADE,
    CONSTRAINT fk_checkout_detalle_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_checkout_detalle_producto FOREIGN KEY (producto_id) REFERENCES producto(id),
    CONSTRAINT fk_checkout_detalle_servicio FOREIGN KEY (servicio_id) REFERENCES servicio(id),
    CONSTRAINT fk_checkout_detalle_cita FOREIGN KEY (cita_id) REFERENCES cita(id),
    INDEX idx_checkout_detalle_orden (empresa_id, checkout_orden_id),
    INDEX idx_checkout_detalle_cita (empresa_id, cita_id)
);

CREATE TABLE intento_pago_checkout (
    id BIGINT NOT NULL AUTO_INCREMENT,
    checkout_orden_id BIGINT NOT NULL,
    empresa_id BIGINT NOT NULL,
    proveedor_pago_id BIGINT NOT NULL,
    idempotencia VARCHAR(128) NOT NULL,
    referencia_externa VARCHAR(180) NULL,
    estado VARCHAR(30) NOT NULL,
    importe DECIMAL(12,2) NOT NULL,
    moneda VARCHAR(10) NOT NULL,
    codigo_respuesta VARCHAR(120) NULL,
    detalle_respuesta VARCHAR(500) NULL,
    creado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_intento_pago_checkout_orden FOREIGN KEY (checkout_orden_id) REFERENCES checkout_orden(id),
    CONSTRAINT fk_intento_pago_checkout_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_intento_pago_checkout_proveedor FOREIGN KEY (proveedor_pago_id) REFERENCES proveedor_pago(id),
    CONSTRAINT uk_intento_pago_checkout_idempotencia UNIQUE (empresa_id, idempotencia),
    INDEX idx_intento_pago_checkout_externo (proveedor_pago_id, referencia_externa)
);
