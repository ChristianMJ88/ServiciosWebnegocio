CREATE TABLE mercado_pago_terminal (
    id BIGINT NOT NULL AUTO_INCREMENT,
    empresa_id BIGINT NOT NULL,
    sucursal_id BIGINT NULL,
    terminal_id VARCHAR(180) NOT NULL,
    pos_id VARCHAR(180) NULL,
    store_id VARCHAR(180) NULL,
    external_pos_id VARCHAR(180) NULL,
    nombre VARCHAR(160) NOT NULL,
    modo_operacion VARCHAR(30) NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_mp_terminal_empresa_terminal (empresa_id, terminal_id),
    KEY idx_mp_terminal_empresa_sucursal (empresa_id, sucursal_id),
    CONSTRAINT fk_mp_terminal_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_mp_terminal_sucursal FOREIGN KEY (sucursal_id) REFERENCES sucursal(id)
);

CREATE TABLE orden_point_caja (
    id BIGINT NOT NULL AUTO_INCREMENT,
    public_id VARCHAR(36) NOT NULL,
    empresa_id BIGINT NOT NULL,
    venta_id BIGINT NOT NULL,
    terminal_id BIGINT NOT NULL,
    proveedor_orden_id VARCHAR(180) NULL,
    proveedor_pago_id VARCHAR(180) NULL,
    idempotencia VARCHAR(128) NOT NULL,
    estado VARCHAR(30) NOT NULL,
    importe DECIMAL(12,2) NOT NULL,
    moneda VARCHAR(10) NOT NULL,
    detalle_estado VARCHAR(180) NULL,
    creado_por_usuario_id BIGINT NOT NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_point_orden_public_id (public_id),
    UNIQUE KEY uk_point_orden_idempotencia (empresa_id, idempotencia),
    UNIQUE KEY uk_point_orden_proveedor (proveedor_orden_id),
    KEY idx_point_orden_empresa_estado (empresa_id, estado),
    CONSTRAINT fk_point_orden_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_point_orden_venta FOREIGN KEY (venta_id) REFERENCES venta(id),
    CONSTRAINT fk_point_orden_terminal FOREIGN KEY (terminal_id) REFERENCES mercado_pago_terminal(id),
    CONSTRAINT fk_point_orden_usuario FOREIGN KEY (creado_por_usuario_id) REFERENCES usuario(id)
);
