CREATE TABLE venta (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    empresa_id BIGINT NOT NULL,
    sucursal_id BIGINT NOT NULL,
    caja_sesion_id BIGINT NOT NULL,
    cliente_id BIGINT NULL,
    cita_id BIGINT NULL,
    folio VARCHAR(40) NOT NULL,
    estado VARCHAR(20) NOT NULL,
    moneda VARCHAR(10) NOT NULL,
    subtotal DECIMAL(12,2) NOT NULL,
    descuento_total DECIMAL(12,2) NOT NULL DEFAULT 0,
    impuestos_total DECIMAL(12,2) NOT NULL DEFAULT 0,
    total DECIMAL(12,2) NOT NULL,
    observaciones VARCHAR(500) NULL,
    creada_por_usuario_id BIGINT NOT NULL,
    creada_en DATETIME NOT NULL,
    actualizada_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_venta_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_venta_sucursal FOREIGN KEY (sucursal_id) REFERENCES sucursal(id),
    CONSTRAINT fk_venta_caja_sesion FOREIGN KEY (caja_sesion_id) REFERENCES caja_sesion(id),
    CONSTRAINT fk_venta_cliente FOREIGN KEY (cliente_id) REFERENCES cliente(usuario_id),
    CONSTRAINT fk_venta_cita FOREIGN KEY (cita_id) REFERENCES cita(id),
    CONSTRAINT fk_venta_usuario FOREIGN KEY (creada_por_usuario_id) REFERENCES usuario(id),
    CONSTRAINT uk_venta_empresa_folio UNIQUE (empresa_id, folio),
    INDEX idx_venta_empresa_sucursal_fecha (empresa_id, sucursal_id, creada_en),
    INDEX idx_venta_empresa_cita (empresa_id, cita_id, estado)
);

CREATE TABLE venta_detalle (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    empresa_id BIGINT NOT NULL,
    venta_id BIGINT NOT NULL,
    tipo_concepto VARCHAR(20) NOT NULL,
    producto_id BIGINT NULL,
    servicio_id BIGINT NULL,
    cita_id BIGINT NULL,
    sku VARCHAR(80) NULL,
    nombre VARCHAR(180) NOT NULL,
    cantidad DECIMAL(14,3) NOT NULL,
    precio_unitario DECIMAL(12,2) NOT NULL,
    descuento DECIMAL(12,2) NOT NULL DEFAULT 0,
    impuestos DECIMAL(12,2) NOT NULL DEFAULT 0,
    total DECIMAL(12,2) NOT NULL,
    CONSTRAINT fk_venta_detalle_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_venta_detalle_venta FOREIGN KEY (venta_id) REFERENCES venta(id) ON DELETE CASCADE,
    CONSTRAINT fk_venta_detalle_producto FOREIGN KEY (producto_id) REFERENCES producto(id),
    CONSTRAINT fk_venta_detalle_servicio FOREIGN KEY (servicio_id) REFERENCES servicio(id),
    CONSTRAINT fk_venta_detalle_cita FOREIGN KEY (cita_id) REFERENCES cita(id),
    INDEX idx_venta_detalle_venta (empresa_id, venta_id),
    INDEX idx_venta_detalle_cita (empresa_id, cita_id)
);

CREATE TABLE pago_venta (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    empresa_id BIGINT NOT NULL,
    venta_id BIGINT NOT NULL,
    caja_sesion_id BIGINT NOT NULL,
    monto DECIMAL(12,2) NOT NULL,
    metodo_pago VARCHAR(30) NOT NULL,
    referencia VARCHAR(120) NULL,
    registrado_por_usuario_id BIGINT NOT NULL,
    registrado_en DATETIME NOT NULL,
    CONSTRAINT fk_pago_venta_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_pago_venta_venta FOREIGN KEY (venta_id) REFERENCES venta(id),
    CONSTRAINT fk_pago_venta_sesion FOREIGN KEY (caja_sesion_id) REFERENCES caja_sesion(id),
    CONSTRAINT fk_pago_venta_usuario FOREIGN KEY (registrado_por_usuario_id) REFERENCES usuario(id),
    INDEX idx_pago_venta_sesion (empresa_id, caja_sesion_id, registrado_en)
);
