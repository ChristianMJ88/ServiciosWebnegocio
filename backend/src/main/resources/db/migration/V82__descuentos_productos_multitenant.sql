CREATE TABLE producto_regla_descuento (
    id BIGINT NOT NULL AUTO_INCREMENT,
    empresa_id BIGINT NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    descripcion VARCHAR(500) NULL,
    alcance VARCHAR(20) NOT NULL,
    producto_id BIGINT NULL,
    categoria_id BIGINT NULL,
    zona_precio_id BIGINT NULL,
    sucursal_id BIGINT NULL,
    tipo_descuento VARCHAR(20) NOT NULL,
    valor DECIMAL(12,2) NOT NULL,
    moneda VARCHAR(10) NULL,
    cantidad_minima DECIMAL(14,3) NOT NULL DEFAULT 1,
    fecha_inicio DATE NULL,
    fecha_fin DATE NULL,
    prioridad INT NOT NULL DEFAULT 0,
    combinable BOOLEAN NOT NULL DEFAULT FALSE,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_producto_descuento_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_producto_descuento_producto FOREIGN KEY (producto_id) REFERENCES producto(id) ON DELETE CASCADE,
    CONSTRAINT fk_producto_descuento_categoria FOREIGN KEY (categoria_id) REFERENCES producto_categoria(id) ON DELETE CASCADE,
    CONSTRAINT fk_producto_descuento_zona FOREIGN KEY (zona_precio_id) REFERENCES producto_zona_precio(id) ON DELETE CASCADE,
    CONSTRAINT fk_producto_descuento_sucursal FOREIGN KEY (sucursal_id) REFERENCES sucursal(id) ON DELETE CASCADE,
    INDEX idx_producto_descuento_resolucion (empresa_id, activa, fecha_inicio, fecha_fin, prioridad),
    INDEX idx_producto_descuento_producto (empresa_id, producto_id, categoria_id)
);
