CREATE TABLE conciliacion_pago (
    id BIGINT NOT NULL AUTO_INCREMENT,
    empresa_id BIGINT NOT NULL,
    proveedor_pago_id BIGINT NOT NULL,
    canal VARCHAR(20) NOT NULL,
    checkout_orden_id BIGINT NULL,
    intento_pago_checkout_id BIGINT NULL,
    orden_point_caja_id BIGINT NULL,
    venta_id BIGINT NULL,
    referencia_orden_externa VARCHAR(180) NOT NULL,
    referencia_pago_externa VARCHAR(180) NULL,
    estado VARCHAR(30) NOT NULL,
    moneda VARCHAR(10) NOT NULL,
    importe_bruto DECIMAL(14,2) NOT NULL,
    comision_proveedor_total DECIMAL(14,2) NULL,
    impuesto_comision_proveedor DECIMAL(14,2) NULL,
    comision_plataforma DECIMAL(14,2) NULL,
    impuesto_comision_plataforma DECIMAL(14,2) NULL,
    retenciones DECIMAL(14,2) NULL,
    importe_reembolsado DECIMAL(14,2) NOT NULL DEFAULT 0,
    importe_neto DECIMAL(14,2) NULL,
    fuente VARCHAR(30) NOT NULL,
    liquidacion_definitiva BOOLEAN NOT NULL DEFAULT FALSE,
    liquidado_en DATETIME(6) NULL,
    creado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    actualizado_en DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (id),
    CONSTRAINT fk_conciliacion_pago_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_conciliacion_pago_proveedor FOREIGN KEY (proveedor_pago_id) REFERENCES proveedor_pago(id),
    CONSTRAINT fk_conciliacion_pago_checkout FOREIGN KEY (checkout_orden_id) REFERENCES checkout_orden(id),
    CONSTRAINT fk_conciliacion_pago_intento FOREIGN KEY (intento_pago_checkout_id) REFERENCES intento_pago_checkout(id),
    CONSTRAINT fk_conciliacion_pago_point FOREIGN KEY (orden_point_caja_id) REFERENCES orden_point_caja(id),
    CONSTRAINT fk_conciliacion_pago_venta FOREIGN KEY (venta_id) REFERENCES venta(id),
    CONSTRAINT uk_conciliacion_pago_orden UNIQUE (proveedor_pago_id, referencia_orden_externa),
    INDEX idx_conciliacion_pago_empresa (empresa_id, estado, actualizado_en),
    INDEX idx_conciliacion_pago_referencia (empresa_id, referencia_pago_externa)
);
